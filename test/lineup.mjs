import puppeteer from 'puppeteer-core';
import http from 'node:http';
import { readFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
const ROOT = path.resolve('dist'), THREE = readFileSync(path.resolve('node_modules/three/build/three.module.min.js'));
const OUT = path.resolve('test/lineup'); mkdirSync(OUT, { recursive: true });
const server = http.createServer((req, res) => { let b = null; try { b = readFileSync(path.join(ROOT, req.url === '/' ? 'index.html' : req.url)); } catch {} if (b) { res.writeHead(200, { 'content-type': 'text/html' }); res.end(b); } else { res.writeHead(404); res.end(); } }).listen(8124);
const browser = await puppeteer.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-background-networking', '--no-first-run'] });
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 720 });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message + '\n' + e.stack));
await page.setRequestInterception(true);
page.on('request', (r) => { const u = r.url(); if (u.includes('cdn.jsdelivr.net/npm/three@0.170.0')) return r.respond({ status: 200, contentType: 'application/javascript', headers: { 'access-control-allow-origin': '*' }, body: THREE }); if (u.includes('fonts.g')) return r.respond({ status: 200, contentType: 'text/css', body: '' }); r.continue(); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await page.goto('http://localhost:8124/');
await sleep(2500);
await page.click('#btn-begin');
await page.evaluate(() => { window.__unsung.game.autoAdvance = true; });
await sleep(6000);
await page.evaluate(() => {
  const g = window.__unsung.game; const P = g.player, C = g.corin;
  g.freezeAI = true; g.ui.hudVisible(false); g.ui.hint(''); g.ui.objective('');
  P.setState('script'); P.pos.set(-2.6, 0, 6); P.facing = 0; P.scriptPose = null;
  C.setState('script'); C.mode = 'idle'; C.pos.set(-1.35, 0, 6); C.facing = 0; C.scriptPose = null;
  const s = g.addExtra(-0.1, 6, 0); s.update = function (dt) { this.sync(); };
  const a = g.spawn('raider', 1.15, 6); a.setState('script'); a.facing = 0;
  const b = g.spawn('shield', 2.45, 6); b.setState('script'); b.facing = 0;
  const v = g.spawnVessa(3.95, 6); v.setState('script'); v.facing = 0;
  g.cam.shot([0.6, 1.45, 10.6], [0.6, 1.15, 6], 0);
  window.__stance = (r) => { };
});
await sleep(1500);
await page.screenshot({ path: OUT + '/lineup-lowres.png' });
await page.evaluate(() => { const g = window.__unsung.game; g.renderer.setSize(1280, 720, false); });
await sleep(600);
await page.screenshot({ path: OUT + '/lineup-hires.png' });
await page.evaluate(() => { const g = window.__unsung.game; g.cam.shot([-1.1, 1.75, 8.2], [-2.0, 1.35, 6], 0); g.player.facing = 0.5; g.corin.facing = -0.3; });
await sleep(700);
await page.screenshot({ path: OUT + '/closeup.png' });
await page.evaluate(() => { const g = window.__unsung.game; g.cam.shot([4.6, 1.8, 3.4], [1.0, 1.1, 6], 0); });
await sleep(700);
await page.screenshot({ path: OUT + '/back34.png' });
console.log('errors:', errors.length); for (const e of errors.slice(0, 10)) console.log(e);
await browser.close(); server.close();
